namespace {

std::string lua_escape(const std::string& s) {
    std::string out;
    out.reserve(s.size());
    for (const char c : s) {
        if (c == '\\') {
            out += "\\\\";
        } else if (c == '"') {
            out += "\\\"";
        } else {
            out += c;
        }
    }
    return out;
}

} // namespace

namespace snapshot_exporter_internal {

std::vector<InstalledEntry> load_sorted_snapshot_entries(const ReqPackConfig& config) {
    HistoryManager history(config);
    std::vector<InstalledEntry> sorted = history.loadInstalledState();
    std::sort(sorted.begin(), sorted.end(), [](const InstalledEntry& a, const InstalledEntry& b) {
        if (a.system != b.system) {
            return a.system < b.system;
        }
        return a.name < b.name;
    });
    return sorted;
}

std::string build_snapshot_rendered_text(const std::vector<InstalledEntry>& entries) {
    std::ostringstream out;
    out << "-- Generated by ReqPack snapshot\n";
    out << "return {\n";
    out << "  packages = {\n";
    for (const InstalledEntry& e : entries) {
        out << "    { system = \"" << lua_escape(e.system) << "\", name = \"" << lua_escape(e.name)
            << "\", version = \"" << lua_escape(e.version) << "\" },\n";
    }
    out << "  },\n";
    out << "}\n";
    return out.str();
}

std::string resolved_output_path(const Request& request) {
    if (!request.outputPath.empty()) {
        return request.outputPath;
    }
    return {};
}

} // namespace snapshot_exporter_internal

std::string SnapshotExporter::resolveOutputPath(const Request& request) const {
    return snapshot_exporter_internal::resolved_output_path(request);
}

std::string SnapshotExporter::render(const std::vector<InstalledEntry>& entries) const {
    return snapshot_exporter_internal::build_snapshot_rendered_text(entries);
}

CommandOutput SnapshotExporter::buildSnapshotOutput(const Request& request) const {
    const std::vector<InstalledEntry> sorted = snapshot_exporter_internal::load_sorted_snapshot_entries(this->config);
    const std::string rendered = render(sorted);
    const std::string outputPath = resolveOutputPath(request);

    CommandOutput output;
    output.mode = DisplayMode::SNAPSHOT;
    output.sessionItems = {"snapshot"};
    output.success = true;
    output.succeeded = 1;

    if (sorted.empty()) {
        output.blocks.push_back(make_command_message_block("snapshot: no installed packages tracked in history. Ensure "
                                                           "history.trackInstalled is enabled in your config."));
    }

    std::vector<CommandOutputField> fields;
    fields.push_back(CommandOutputField {.key = "Format", .value = "reqpack.lua"});
    fields.push_back(CommandOutputField {.key = "Package Count", .value = std::to_string(sorted.size())});
    if (outputPath.empty()) {
        fields.push_back(CommandOutputField {.key = "Output", .value = "stdout"});
        output.blocks.push_back(make_command_field_value_block(fields));
        output.blocks.push_back(make_command_raw_text_block(rendered));
        return output;
    }

    std::filesystem::path filePath(outputPath);
    if (filePath.is_relative()) {
        filePath = std::filesystem::current_path() / filePath;
    }
    fields.push_back(CommandOutputField {.key = "Output Path", .value = filePath.string()});
    output.blocks.push_back(make_command_field_value_block(fields));
    output.blocks.push_back(make_command_artifact_block("artifact", filePath.string()));
    return output;
}

namespace snapshot_exporter_internal {

bool write_snapshot_output(const ReqPackConfig& config, const Request& request,
                           const std::vector<InstalledEntry>& entries, const std::string& rendered,
                           const std::string& outputPath) {
    if (entries.empty()) {
        Logger::instance().emit(OutputAction::DISPLAY_MESSAGE,
                                OutputContext {.message = "snapshot: no installed packages tracked in history. Ensure "
                                                          "history.trackInstalled is enabled in your config."});
    }

    if (outputPath.empty()) {
        render_command_output(SnapshotExporter(config).buildSnapshotOutput(request));
        return true;
    }

    const bool force = std::find(request.flags.begin(), request.flags.end(), "force") != request.flags.end();
    const report_output::ReportFileWriteConfig writeConfig {.skipWhenExistsWithoutForceInNonInteractiveMode = false};
    if (!report_output::write_report_file(rendered, outputPath, force, config.interaction.interactive, writeConfig,
                                          [](const std::string& resolvedPath,
                                             const report_output::ReportWriteFailure failure) {
                                              switch (failure) {
                                              case report_output::ReportWriteFailure::CreateDirectory:
                                                  return make_error_diagnostic(
                                                      "snapshot", "snapshot: failed to create output directory: " +
                                                                      resolvedPath,
                                                      "ReqPack could not create parent directory for snapshot output.",
                                                      "Check target path permissions and parent directory state, then "
                                                      "retry.",
                                                      {}, "snapshot", "output");
                                              case report_output::ReportWriteFailure::OpenFile:
                                                  return make_error_diagnostic(
                                                      "snapshot", "snapshot: failed to open output path: " + resolvedPath,
                                                      "ReqPack could not open requested snapshot output file for writing.",
                                                      "Check whether path points to writable file location and retry.", {},
                                                      "snapshot", "output");
                                              case report_output::ReportWriteFailure::WriteFile:
                                                  return make_error_diagnostic(
                                                      "snapshot", "snapshot: failed to write output path: " + resolvedPath,
                                                      "ReqPack could not finish writing snapshot manifest to output file.",
                                                      "Check disk space, filesystem health, and write permissions, then "
                                                      "retry.",
                                                      {}, "snapshot", "output");
                                              }
                                              return make_error_diagnostic(
                                                  "snapshot", "snapshot: failed to write output path: " + resolvedPath,
                                                  "ReqPack could not finish writing snapshot manifest to output file.",
                                                  "Check disk space, filesystem health, and write permissions, then retry.",
                                                  {}, "snapshot", "output");
                                          })) {
        return false;
    }

    render_command_output(SnapshotExporter(config).buildSnapshotOutput(request));
    return true;
}

} // namespace snapshot_exporter_internal

bool SnapshotExporter::exportSnapshot(const Request& request) const {
    const std::vector<InstalledEntry> entries = snapshot_exporter_internal::load_sorted_snapshot_entries(this->config);
    const std::string rendered = render(entries);
    const std::string outputPath = resolveOutputPath(request);
    return snapshot_exporter_internal::write_snapshot_output(this->config, request, entries, rendered, outputPath);
}
